// Class title rendering only; deterministic weapon damage and combat paths.
const assert = require('node:assert/strict');
const { fixture } = require('./test-leviathans-wake.cjs');
const titleCount = (message,title) => message.split(title).length-1;
async function main() {
  const f=await fixture(50);
  const attack=(id,rolls,tier,protection=0) => f.c.resolveWeaponAttack(id,rolls,9,protection,'discord',tier);
  const knight0=attack('sword-and-shield',[4],0);
  assert(knight0.message.includes('+2 Wayward Knight'));
  assert(attack('sword-and-shield',[7],1).message.includes('+3 Shieldbearer'));
  const paladin=attack('sword-and-shield',[4],5);
  assert.equal(paladin.damage,29);
  assert.equal(paladin.protection,10);
  assert(paladin.message.includes('+5 Nexus Paladin'));
  assert.equal(titleCount(paladin.message,'Nexus Paladin'),1);
  assert(!paladin.message.includes('+5 Knight'));
  const rogue=attack('daggers',[14,19],5);
  assert.equal(rogue.damage,49);
  assert(rogue.message.includes('+4 Nexus Phantom +4 Both Blades'));
  assert(!rogue.message.includes('+4 Rogue'));
  assert(attack('daggers',[15,19],5).message.includes('+6 High Pair'));
  const axe=attack('axe',[20],5);
  assert.equal(axe.damage,99);
  assert(axe.message.includes('+5 Worldbreaker +15 Natural 20'));
  assert(!axe.message.includes('Berserker'));
  const spear=attack('spear',[18],5,20);
  assert.equal(spear.damage,53);
  assert.equal(spear.pierceProtection,15);
  assert(spear.message.includes('+4 Horizon Dragoon +5 Protection Bonus'));
  assert.equal(titleCount(spear.message,'Horizon Dragoon'),1);
  assert(attack('spear',[18],1).message.includes('+3 Lancer'));
  assert(attack('spear',[18],4).message.includes('+4 Crownlance'));
  const hammer=attack('hammer',[20],5);
  assert.equal(hammer.damage,73);
  assert.equal(hammer.stagger,12);
  assert(hammer.message.includes('+4 Titan Vanguard'));
  assert(hammer.message.includes('Stagger: next successful enemy attack -12 damage'));
  assert(!hammer.message.includes('+4 Vanguard'));
  const bow=attack('bow',[20,20],5);
  assert.equal(bow.damage,69);
  assert(bow.message.includes('+5 Horizon Hunter +15 Double 20'));
  assert.equal(titleCount(bow.message,'Horizon Hunter'),1);
  assert(!bow.message.includes('+5 Ranger'));
  assert(attack('bow',[15,19],3).message.includes('+4 Deadeye +4 High Pair'));
  assert(attack('bow',[15,19],5).message.includes('+5 Horizon Hunter +8 High Pair'));
  for(const id of ['sword-and-shield','daggers','axe','spear','hammer','bow']) {
    const rolls=id==='daggers'||id==='bow'?[14,19]:[17];
    const plain=f.c.resolveWeaponAttack(id,rolls,9,0,'discord');
    assert(!plain.message.includes('+5 Nexus Paladin'));
    assert(!plain.message.includes('Worldbreaker'));
    assert(!plain.message.includes('Horizon Hunter'));
  }
  const mismatch=await fixture(50);
  await mismatch.editProgress(p=>{p.ownedWeapons=['bow','sword-and-shield'];p.equippedWeapon='bow';p.activeClass='sword-and-shield';p.stats.strength=9;});
  mismatch.rolls.push(11,18,1);
  const mismatchedAttack=await mismatch.attack();
  assert(mismatchedAttack.message.includes('30 +9 Strength → 39 dmg'));
  assert(!mismatchedAttack.message.includes('Nexus Paladin'));
  assert(!mismatchedAttack.message.includes('Horizon Hunter'));
  const victory=await fixture(50);
  await victory.editProgress(p=>{p.ownedWeapons=['sword-and-shield'];p.equippedWeapon='sword-and-shield';p.activeClass='sword-and-shield';p.stats.strength=9;});
  await victory.editState(s=>{s.enemy.hp=1;s.playerHp=90;});
  victory.rolls.push(4);
  const win=await victory.attack();
  assert.equal(win.won,true);
  assert(win.message.includes('+5 Nexus Paladin → 29 dmg'));
  assert.equal(titleCount(win.message,'Nexus Paladin'),1);
  assert(win.message.includes('Restored 3 HP'));
  assert(!win.message.includes('Nexus Paladin — Restored'));
  const twitch=await fixture(50,'twitch');
  await twitch.editProgress(p=>{p.ownedWeapons=['bow'];p.equippedWeapon='bow';p.activeClass='bow';p.stats.strength=9;});
  twitch.rolls.push(20,20,1);
  const twitchAttack=await twitch.attack();
  assert(twitchAttack.message.includes('+5 Horizon Hunter +15 Double 20'));
  assert.equal(titleCount(twitchAttack.message,'Horizon Hunter'),1);
  console.log('Six class title families, conditional labels, victory, mismatch, and Twitch receipts passed.');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
